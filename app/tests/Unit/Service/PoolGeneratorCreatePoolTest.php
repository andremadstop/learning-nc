<?php
declare(strict_types=1);

namespace OCA\Learning\Tests\Unit\Service;

use OCA\Learning\Db\Pool;
use OCA\Learning\Service\Llm\LlmGateway;
use OCA\Learning\Service\LlmService;
use OCA\Learning\Service\PoolGeneratorService;
use OCA\Learning\Service\PoolService;
use OCA\Learning\Service\QuestionService;
use PHPUnit\Framework\Attributes\AllowMockObjectsWithoutExpectations;
use PHPUnit\Framework\MockObject\MockObject;
use PHPUnit\Framework\TestCase;
use Psr\Log\LoggerInterface;

/**
 * Audit #164: createPool() created the pool before looking at the questions, so drafts that all
 * failed left an empty 'Generated by AI Pool Generator' pool behind, reported as imported=0.
 */
#[AllowMockObjectsWithoutExpectations]
class PoolGeneratorCreatePoolTest extends TestCase {
    private PoolService&MockObject $pools;
    private QuestionService&MockObject $questions;

    protected function setUp(): void {
        $this->pools = $this->createMock(PoolService::class);
        $this->questions = $this->createMock(QuestionService::class);
    }

    private function service(): PoolGeneratorService {
        return new PoolGeneratorService(
            $this->createMock(LlmService::class),
            $this->createMock(LlmGateway::class),
            $this->pools,
            $this->questions,
            $this->createMock(LoggerInterface::class),
            $this->createMock(\OCP\Files\IRootFolder::class),
        );
    }

    private static function pool(int $id): Pool {
        $pool = new Pool();
        $pool->setId($id);
        return $pool;
    }

    /** @return array<string, mixed> */
    private static function question(string $text): array {
        return ['text' => $text, 'answers' => [['text' => 'A', 'is_correct' => true], ['text' => 'B']]];
    }

    public function testDraftsWithoutAUsableQuestionCreateNoPool(): void {
        $this->pools->expects($this->never())->method('create');

        $this->expectException(\RuntimeException::class);
        $this->expectExceptionMessage('No valid questions to import');
        $this->service()->createPool('VLANs', [
            ['text' => 'only one answer', 'answers' => [['text' => 'A', 'is_correct' => true]]],
            ['text' => '', 'answers' => []],
        ], 'teacher');
    }

    public function testAPoolWhoseQuestionsAllFailIsRemovedAgain(): void {
        $this->pools->expects($this->once())->method('create')->willReturn(self::pool(41));
        $this->questions->method('create')->willThrowException(new \InvalidArgumentException('no correct answer'));
        $this->pools->expects($this->once())->method('delete')->with(41, 'teacher');

        $this->expectException(\RuntimeException::class);
        $this->expectExceptionMessage('No valid questions to import');
        $this->service()->createPool('VLANs', [self::question('Q1'), self::question('Q2')], 'teacher');
    }

    public function testAPoolWithOneImportedQuestionStays(): void {
        $this->pools->method('create')->willReturn(self::pool(42));
        $this->questions->method('create')->willReturnOnConsecutiveCalls(
            $this->throwException(new \InvalidArgumentException('bad')),
            ['id' => 1],
        );
        $this->pools->expects($this->never())->method('delete');

        $result = $this->service()->createPool('VLANs', [self::question('Q1'), self::question('Q2')], 'teacher');

        $this->assertSame(['pool_id' => 42, 'imported' => 1], $result);
    }
}
