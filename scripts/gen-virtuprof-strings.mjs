#!/usr/bin/env node
/**
 * Canonical generator + guard for app/src/l10n/virtuprof-strings.js.
 *
 * WHY THIS EXISTS
 * ---------------
 * VirtuProf does not translate through Nextcloud's t('learning', …). It carries its
 * own runtime catalogue and resolves with translateVirtuProf(lang, key), because the
 * assistant renders strings the server never sees (FAQ bodies, scripted step text).
 * That catalogue's own header said "Extracted from app/l10n/*.json" — it was generated
 * once, by hand, and then drifted for months with no generator to regenerate it.
 *
 * Codeberg #6 (2026-09-11) is the bill: 161 of 345 reachable keys were absent from the
 * catalogue, so translateVirtuProf() fell through to the raw source string and rendered
 * German FAQ answers inside a Ukrainian UI. 63 of those 161 were already translated in
 * l10n/uk.json — pure staleness, not a translation gap.
 *
 * The four gates in check-i18n-parity.sh could not see any of it: gates 1-3 compare the
 * language files against each other, and gate 4 (check-i18n-coverage.py) scans for
 * t('learning', …) call sites, which VirtuProf has none of. This file is gate 5.
 *
 * WHAT IT DOES
 *   1. Collects every key VirtuProf can reach (see collectKeys below).
 *   2. Requires each one to exist in l10n/de.json — that is the coverage half. A key
 *      only in the source would otherwise generate a catalogue entry equal to itself
 *      and render German in all six languages, silently, exactly as before.
 *   3. Writes the six dicts from l10n/<lang>.json.
 *
 * Because the keys now have to live in l10n/*.json, the existing gates 1-4 cover the
 * VirtuProf strings too. One artefact, one source of truth.
 *
 * THE DANGEROUS PART — why nothing is ever dropped silently
 * --------------------------------------------------------
 * A generator that rewrites a catalogue deletes everything it cannot see. The first
 * version of this file did exactly that: it removed 68 working keys, among them all 36
 * onboarding slide titles, because they reach vt() as vt(currentSlide.titleKey) and a
 * literal scan cannot resolve a variable. Symbolic keys like `slide:student:welcome:title`
 * have no readable fallback either — translateVirtuProf() returns the key itself, so the
 * wizard would have rendered `slide:student:welcome:title` on screen.
 *
 * So the catalogue is the union of two sets:
 *   RESOLVED — found by the scanner or an imported catalogue. These MUST exist in
 *              l10n/de.json; a missing one fails the build (the coverage half).
 *   CARRIED  — already in the committed catalogue and still in l10n/de.json. Kept as-is.
 *              This is the safety net for every vt(variable) call the scanner cannot
 *              resolve. A key leaves the catalogue only when it leaves l10n/de.json,
 *              which is a deliberate act, not an oversight.
 *
 * Run with --list-indirect to see the vt(variable) call sites that rely on the net.
 *
 * Usage:
 *   node scripts/gen-virtuprof-strings.mjs                  # regenerate the catalogue
 *   node scripts/gen-virtuprof-strings.mjs --check          # verify; exit 1 on drift
 *   node scripts/gen-virtuprof-strings.mjs --list-indirect  # unresolvable vt() call sites
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const APP = path.join(ROOT, 'app')
const SRC = path.join(APP, 'src')
const L10N = path.join(APP, 'l10n')
const SCRIPTS_MODULE = path.join(SRC, 'utils', 'virtuprof-scripts.js')
const SLIDES_MODULE = path.join(SRC, 'utils', 'onboarding-slides.js')
const TARGET = path.join(SRC, 'l10n', 'virtuprof-strings.js')

const LANGS = ['de', 'en', 'fr', 'ru', 'ar', 'uk']
const HEADER = '// Generated by scripts/gen-virtuprof-strings.mjs from app/l10n/*.json — do not edit by hand.'

/**
 * Strings that look like keys but are pure passthrough placeholders: the gameshow
 * scripts set step.text to '{commentary}' / '{message}' and the caller substitutes the
 * whole thing. Translating them is meaningless; leaving them out of the ignore list
 * makes the gate demand catalogue entries for them forever.
 */
const IGNORED_KEYS = new Set(['{commentary}', '{message}'])

/** Literal vt('…') and this.vt('…') — the per-component translateVirtuProf wrapper. */
const VT_CALL = /(?:\bthis\.)?\bvt\(\s*(['"`])((?:\\.|(?!\1)[\s\S])*?)\1/g
/** Literal translateVirtuProf(lang, '…') — used where no vt() wrapper exists. */
const TVP_CALL = /\btranslateVirtuProf\(\s*[^,()]+,\s*(['"`])((?:\\.|(?!\1)[\s\S])*?)\1/g
/** vt(<expression>) — reported by --list-indirect; these are what CARRIED protects. */
const VT_INDIRECT = /(?:\bthis\.)?\bvt\(\s*(?!['"`]|key\b)([A-Za-z_$][^)]*)\)/g

const ESCAPES = { n: '\n', t: '\t', r: '\r', b: '\b', f: '\f', v: '\v', 0: '\0' }

function unescapeLiteral(raw) {
  return raw.replace(/\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|[\s\S])/g, (_m, g) => {
    if (g.startsWith('u{')) return String.fromCodePoint(parseInt(g.slice(2, -1), 16))
    if (g[0] === 'u') return String.fromCharCode(parseInt(g.slice(1), 16))
    if (g[0] === 'x') return String.fromCharCode(parseInt(g.slice(1), 16))
    if (g === '\n') return ''  // line continuation
    return Object.prototype.hasOwnProperty.call(ESCAPES, g) ? ESCAPES[g] : g
  })
}

function walkSources(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walkSources(full, out)
    else if (/\.(js|vue)$/.test(entry.name)) out.push(full)
  }
  return out
}

/**
 * Every key VirtuProf can reach, mapped to the files that reach it.
 *
 * Two sources, deliberately different techniques:
 *   - virtuprof-scripts.js is IMPORTED, not scanned. Its SCRIPTS/FAQS/FAQ_CATEGORIES are
 *     nested object literals; a regex over them would silently miss a field the day
 *     someone adds one. The import sees exactly what the runtime sees.
 *   - .vue files cannot be imported here, so their vt() literals are matched by regex.
 *     A vt(someVariable) call is therefore invisible to this function — the CARRIED set
 *     in build() is what keeps those keys alive. `--list-indirect` lists them.
 *
 * @returns {Map<string, Set<string>>} key -> set of source files, relative to app/src
 */
async function collectKeys() {
  const keys = new Map()
  const add = (key, file) => {
    if (typeof key !== 'string' || key === '' || IGNORED_KEYS.has(key)) return
    if (!keys.has(key)) keys.set(key, new Set())
    keys.get(key).add(path.relative(SRC, file))
  }

  for (const file of walkSources(SRC)) {
    const text = fs.readFileSync(file, 'utf8')
    for (const re of [VT_CALL, TVP_CALL]) {
      re.lastIndex = 0
      let m
      while ((m = re.exec(text)) !== null) add(unescapeLiteral(m[2]), file)
    }
  }

  const { SCRIPTS, FAQS, FAQ_CATEGORIES } = await import(pathToFileURL(SCRIPTS_MODULE).href)
  for (const script of Object.values(SCRIPTS)) {
    for (const step of script.steps || []) {
      add(step.text, SCRIPTS_MODULE)
      add(step.title, SCRIPTS_MODULE)
    }
  }
  for (const category of Object.values(FAQ_CATEGORIES)) {
    for (const field of ['label', 'title', 'description']) add(category[field], SCRIPTS_MODULE)
  }
  for (const faq of Object.values(FAQS)) {
    for (const field of ['label', 'title', 'text']) add(faq[field], SCRIPTS_MODULE)
  }

  // OnboardingIntro renders vt(currentSlide.titleKey) / vt(currentSlide.textKey), so the
  // scanner never sees these 36 symbolic keys. They are resolvable by import, and they
  // matter more than most: a symbolic key has no readable fallback, so a missing entry
  // puts the literal text `slide:student:welcome:title` in front of the user.
  // The module exports several slide decks (STUDENT_SLIDES, INSTRUCTOR_SLIDES, …); walk
  // every exported array so a deck added later is picked up without touching this file.
  const slidesModule = await import(pathToFileURL(SLIDES_MODULE).href)
  for (const deck of Object.values(slidesModule)) {
    if (!Array.isArray(deck)) continue
    for (const slide of deck) {
      add(slide?.titleKey, SLIDES_MODULE)
      add(slide?.textKey, SLIDES_MODULE)
    }
  }

  return keys
}

/** vt(<expression>) call sites — the ones the CARRIED set exists for. */
function collectIndirectCallSites() {
  const sites = []
  for (const file of walkSources(SRC)) {
    const text = fs.readFileSync(file, 'utf8')
    VT_INDIRECT.lastIndex = 0
    let m
    while ((m = VT_INDIRECT.exec(text)) !== null) {
      const line = text.slice(0, m.index).split('\n').length
      sites.push({ file: path.relative(SRC, file), line, expr: m[1].trim().slice(0, 70) })
    }
  }
  return sites
}

function loadCatalogue(lang) {
  const file = path.join(L10N, `${lang}.json`)
  return JSON.parse(fs.readFileSync(file, 'utf8')).translations
}

function render(keys, catalogues) {
  const sorted = [...keys].sort()
  const blocks = LANGS.map(lang => {
    const tr = catalogues[lang]
    const lines = sorted.map(
      key => `  ${JSON.stringify(key)}: ${JSON.stringify(tr[key])},`
    )
    // Drop the trailing comma on the last entry to match hand-written object style.
    if (lines.length > 0) lines[lines.length - 1] = lines[lines.length - 1].slice(0, -1)
    return `export const ${lang} = {\n${lines.join('\n')}\n}`
  })
  return `${HEADER}\n${blocks.join('\n\n')}\n`
}

/** Keys the committed catalogue already carries, so nothing is dropped silently. */
function committedKeys() {
  if (!fs.existsSync(TARGET)) return []
  const text = fs.readFileSync(TARGET, 'utf8')
  const firstBlock = text.slice(text.indexOf('export const de = {'), text.indexOf('\n}'))
  return [...firstBlock.matchAll(/^ {2}("(?:\\.|[^"])*")\s*:/gm)].map(m => JSON.parse(m[1]))
}

async function build() {
  const keys = await collectKeys()
  const catalogues = Object.fromEntries(LANGS.map(lang => [lang, loadCatalogue(lang)]))

  // Coverage half: a reachable key that is in no language file renders as its own raw
  // source text in every language. That is the Codeberg #6 defect; fail on it here.
  const missing = [...keys.keys()].filter(key => !(key in catalogues.de)).sort()
  if (missing.length > 0) {
    console.error(`FAIL: ${missing.length} VirtuProf key(s) reachable from the source but absent from l10n/de.json.`)
    console.error('Without a catalogue entry translateVirtuProf() falls back to the raw source string,')
    console.error('so these render in their source language (German or English) in ALL six languages.')
    console.error('')
    for (const key of missing.slice(0, 15)) {
      const where = [...keys.get(key)].join(', ')
      const shown = key.length > 90 ? `${key.slice(0, 90)}…` : key
      console.error(`  ${JSON.stringify(shown)}\n      reached from: ${where}`)
    }
    if (missing.length > 15) console.error(`  … and ${missing.length - 15} more`)
    console.error('')
    console.error('Fix: add each key to all six app/l10n/<lang>.json files (German source convention),')
    console.error('     then run: python3 scripts/l10n_js_sync.py && node scripts/gen-virtuprof-strings.mjs')
    return { ok: false }
  }

  // CARRIED: keys the committed catalogue holds that the scanner cannot resolve. They stay
  // as long as l10n/de.json still has them. Without this the generator would delete every
  // vt(variable) key on its first run — which is exactly what its first version did, taking
  // all 36 onboarding slide titles with it.
  const resolved = new Set(keys.keys())
  const carried = committedKeys().filter(key => !resolved.has(key) && key in catalogues.de)
  const final = new Set([...resolved, ...carried])

  // A language file missing a key that de.json has is gate 1's job, not ours; guard
  // anyway so a partial catalogue cannot render `undefined` into the bundle.
  const holes = []
  for (const lang of LANGS) {
    for (const key of final) {
      if (!(key in catalogues[lang])) holes.push(`${lang}: ${JSON.stringify(key.slice(0, 60))}`)
    }
  }
  if (holes.length > 0) {
    console.error(`FAIL: ${holes.length} key(s) present in de.json but missing from another language file.`)
    for (const hole of holes.slice(0, 10)) console.error(`  ${hole}`)
    console.error('Fix: run scripts/check-i18n-parity.sh — this is key-set parity drift.')
    return { ok: false }
  }

  return {
    ok: true,
    content: render(final, catalogues),
    count: final.size,
    resolvedCount: resolved.size,
    carriedCount: carried.length,
  }
}

async function main() {
  if (process.argv.includes('--list-indirect')) {
    const sites = collectIndirectCallSites()
    console.log(`${sites.length} vt(<expression>) call site(s) the scanner cannot resolve.`)
    console.log('Their keys survive because the committed catalogue carries them forward;')
    console.log('they are only dropped when the key leaves l10n/de.json.\n')
    for (const site of sites) console.log(`  ${site.file}:${site.line}  vt(${site.expr})`)
    return
  }

  const check = process.argv.includes('--check')
  const result = await build()
  if (!result.ok) process.exit(1)

  const actual = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : ''
  if (!check) {
    fs.writeFileSync(TARGET, result.content, 'utf8')
    const verb = actual === result.content ? 'unchanged' : 'regenerated'
    console.log(`virtuprof-strings.js ${verb} — ${result.count} keys × ${LANGS.length} languages `
      + `(${result.resolvedCount} resolved, ${result.carriedCount} carried)`)
    return
  }

  if (actual === result.content) {
    console.log(`VirtuProf catalogue OK — ${result.count} keys × ${LANGS.length} languages, `
      + `in sync with l10n/*.json (${result.resolvedCount} resolved, ${result.carriedCount} carried `
      + `from vt(<expression>) call sites — see --list-indirect)`)
    return
  }

  console.error('FAIL: app/src/l10n/virtuprof-strings.js is out of sync with app/l10n/*.json')
  const actualLines = actual.split('\n')
  const expectedLines = result.content.split('\n')
  const actualSet = new Set(actualLines)
  const expectedSet = new Set(expectedLines)
  const added = expectedLines.filter(l => l.trim() && !actualSet.has(l))
  const removed = actualLines.filter(l => l.trim() && !expectedSet.has(l))
  for (const line of added.slice(0, 8)) console.error(`  + ${line.trim().slice(0, 120)}`)
  if (added.length > 8) console.error(`  + … ${added.length - 8} more added lines`)
  for (const line of removed.slice(0, 8)) console.error(`  - ${line.trim().slice(0, 120)}`)
  if (removed.length > 8) console.error(`  - … ${removed.length - 8} more removed lines`)
  console.error('')
  console.error('Fix: node scripts/gen-virtuprof-strings.mjs   (regenerates from l10n/*.json)')
  process.exit(1)
}

main().catch(err => {
  console.error('gen-virtuprof-strings.mjs crashed:', err)
  process.exit(1)
})
